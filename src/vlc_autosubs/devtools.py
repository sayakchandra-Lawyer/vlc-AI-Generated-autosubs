"""Developer commands: `uv run autosubs-build` and `uv run autosubs-reproduce`.

A build is a standalone folder (no Python needed) made with PyInstaller for
the platform it runs on, packed as dist/vlc-autosubs-<version>-<platform>.zip (Windows) or .tar.gz.
Builds for other platforms come from CI (.github/workflows/release.yml).
"""

import argparse
import datetime
import os
import platform
import shutil
import subprocess
import sys
import tarfile
import zipfile
from importlib import metadata

from vlc_autosubs import __version__

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

SPEC = r'''# Generated by autosubs-build; edit devtools.py instead.
import sys
from PyInstaller.utils.hooks import collect_all, collect_data_files

datas, binaries, hiddenimports = [], [], []
for pkg in ("faster_whisper", "ctranslate2", "av", "onnxruntime", "tokenizers"):
    d, b, h = collect_all(pkg)
    datas += d; binaries += b; hiddenimports += h
datas += collect_data_files("vlc_autosubs")  # the Lua scripts

a = Analysis([{cli!r}, {helper!r}], binaries=binaries, datas=datas,
             hiddenimports=hiddenimports, excludes=["tkinter", "pytest", "PyInstaller"])
pyz = PYZ(a.pure)
without = lambda entry: [s for s in a.scripts if s[0] != entry]
cli = EXE(pyz, without("helper_entry"), [], exclude_binaries=True,
          name="vlc-autosubs", console=True)
# Windowless on Windows, so no console pops up while VLC runs it.
helper = EXE(pyz, without("cli_entry"), [], exclude_binaries=True,
             name="vlc-autosubs-helper", console=sys.platform != "win32")
COLLECT(cli, helper, a.binaries, a.datas, name="vlc-autosubs")
'''

QUICKSTART = """AutoSubs {version} for {platform}
=============================
Automatic English subtitles for VLC. Full guide:
https://github.com/sayakchandra-Lawyer/vlc-AI-Generated-autosubs

1. Quit VLC.
2. Install:
   Windows: double-click vlc-autosubs.exe
   macOS:   open Terminal in this folder and run
              xattr -dr com.apple.quarantine .
              ./vlc-autosubs install
   Linux:   ./vlc-autosubs install
3. Start VLC and play a video.

The installer copies AutoSubs into VLC's folder, so you can delete this
folder afterwards. To remove AutoSubs: vlc-autosubs uninstall
"""


def platform_tag():
    system = {"Windows": "windows", "Darwin": "macos", "Linux": "linux"}.get(
        platform.system(), platform.system().lower())
    machine = platform.machine().lower()
    arch = {"amd64": "x64", "x86_64": "x64", "arm64": "arm64", "aarch64": "arm64"}.get(machine, machine)
    return f"{system}-{arch}"


def git_commit():
    try:
        out = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                             text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT,
                               capture_output=True, text=True).stdout.strip()
        return out + (" (with uncommitted changes)" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown (not a git checkout)"


def runtime_requirements():
    """Exact versions of everything the app needs (like `pip freeze`, minus dev tools)."""
    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name

    pinned, todo = {}, ["vlc-autosubs"]
    while todo:
        name = canonicalize_name(todo.pop())
        if name in pinned:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        pinned[name] = dist.version
        for req in dist.requires or []:
            r = Requirement(req)
            if r.marker is None or r.marker.evaluate({"extra": ""}):
                todo.append(r.name)
    pinned.pop("vlc-autosubs", None)
    return [f"{n}=={v}" for n, v in sorted(pinned.items())]


def build(bundle_model=None, out_dir=None):
    try:
        import PyInstaller.__main__
    except ImportError:
        sys.exit("PyInstaller is missing. Run builds from a checkout with the dev tools:\n"
                 "  uv run autosubs-build")
    out_dir = os.path.abspath(out_dir or os.path.join(ROOT, "dist"))
    work = os.path.join(ROOT, "build")
    os.makedirs(work, exist_ok=True)

    entries = {
        "cli_entry": "from vlc_autosubs.cli import main\nmain()\n",
        "helper_entry": "from vlc_autosubs.helper import main\nmain()\n",
    }
    paths = {}
    for name, code in entries.items():
        paths[name] = os.path.join(work, name + ".py")
        with open(paths[name], "w", encoding="utf-8") as f:
            f.write(code)
    spec = os.path.join(work, "vlc-autosubs.spec")
    with open(spec, "w", encoding="utf-8") as f:
        f.write(SPEC.format(cli=paths["cli_entry"], helper=paths["helper_entry"]))

    pyi_dist = os.path.join(work, "dist")
    PyInstaller.__main__.run([spec, "--noconfirm", "--clean",
                              "--distpath", pyi_dist, "--workpath", os.path.join(work, "pyi")])
    app = os.path.join(pyi_dist, "vlc-autosubs")

    tag = platform_tag()
    if bundle_model:
        from vlc_autosubs.helper import download_model
        print(f"bundling model '{bundle_model}'…")
        download_model(bundle_model, output_dir=os.path.join(app, "models", bundle_model))

    reqs = runtime_requirements()
    with open(os.path.join(app, "requirements.txt"), "w", encoding="utf-8") as f:
        f.write("# Exact package versions in this build\n" + "\n".join(reqs) + "\n")
    with open(os.path.join(app, "BUILDINFO.txt"), "w", encoding="utf-8") as f:
        f.write(f"AutoSubs {__version__}\n"
                f"platform: {tag}\n"
                f"model: {bundle_model or 'none bundled (downloaded on first use)'}\n"
                f"python: {sys.version.split()[0]}\n"
                f"commit: {git_commit()}\n"
                f"built: {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d %H:%M UTC}\n"
                f"reproduce: uv run autosubs-reproduce v{__version__}"
                + (f" --bundle-model {bundle_model}" if bundle_model else "") + "\n")
    with open(os.path.join(app, "README.txt"), "w", encoding="utf-8") as f:
        f.write(QUICKSTART.format(version=__version__, platform=tag))
    shutil.copy2(os.path.join(ROOT, "LICENSE"), os.path.join(app, "LICENSE.txt"))

    name = f"vlc-autosubs-{__version__}-{tag}" + (f"-offline-{bundle_model}" if bundle_model else "")
    os.makedirs(out_dir, exist_ok=True)
    top = f"vlc-autosubs-{__version__}"
    if platform.system() == "Windows":
        archive = os.path.join(out_dir, name + ".zip")
        with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, allowZip64=True) as z:
            for root, _dirs, files in os.walk(app):
                for fn in files:
                    path = os.path.join(root, fn)
                    z.write(path, os.path.join(top, os.path.relpath(path, app)))
    else:
        # tar keeps the executable bits that zip extractors often drop
        archive = os.path.join(out_dir, name + ".tar.gz")
        with tarfile.open(archive, "w:gz") as t:
            t.add(app, arcname=top)
    print(f"\nbuilt {archive} ({os.path.getsize(archive) / 1e6:.0f} MB)")
    return archive


def build_main():
    ap = argparse.ArgumentParser(prog="autosubs-build",
                                 description="Build a standalone AutoSubs for this platform.")
    ap.add_argument("--bundle-model", metavar="MODEL",
                    help="include a Whisper model for offline use (e.g. small)")
    ap.add_argument("--out", help="output folder (default: dist/)")
    args = ap.parse_args()
    build(args.bundle_model, args.out)


def reproduce_main():
    ap = argparse.ArgumentParser(
        prog="autosubs-reproduce",
        description="Rebuild a tagged release from its exact locked dependencies.")
    ap.add_argument("tag", help="release tag, e.g. v1.1.0")
    ap.add_argument("--bundle-model", metavar="MODEL")
    args = ap.parse_args()
    tree = os.path.join(ROOT, "build", "reproduce-" + args.tag)
    if not os.path.exists(tree):
        subprocess.run(["git", "worktree", "add", "--detach", tree, args.tag], cwd=ROOT, check=True)
    cmd = ["uv", "run", "--locked", "--directory", tree, "autosubs-build",
           "--out", os.path.join(ROOT, "dist", "reproduced")]
    if args.bundle_model:
        cmd += ["--bundle-model", args.bundle_model]
    subprocess.run(cmd, check=True)
